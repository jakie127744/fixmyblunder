// One-off: downloads the Latin subset of the three fonts from Google Fonts into public/fonts and writes public/css/fonts.css.
// Run it again only if you change the font list. The app itself never contacts Google.
import { writeFile, mkdir } from 'node:fs/promises';
const CSS = 'https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,500;12..96,700&family=Figtree:wght@400;500;600;700&family=JetBrains+Mono:wght@500;600&display=swap';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36';
const css = await (await fetch(CSS, { headers: { 'User-Agent': UA } })).text();
await mkdir(new URL('../public/fonts/', import.meta.url), { recursive: true });
const seen = new Map(); let out = '/* Self-hosted Latin subsets. Generated by scripts/fetch-fonts.mjs. Licences: SIL OFL 1.1 (see THIRD_PARTY_NOTICES.md). */\n';
for (const m of css.matchAll(/\/\* (\S+) \*\/\s*@font-face\s*\{([^}]*)\}/g)) {
  if (m[1] !== 'latin') continue;
  const body = m[2];
  const fam = /font-family:\s*'([^']+)'/.exec(body)[1];
  const url = /url\(([^)]+)\)/.exec(body)[1];
  const slug = fam.toLowerCase().replace(/\s+/g, '-');
  const wght = /font-weight:\s*([^;]+)/.exec(body)[1].trim().replace(/\s+/g, '-');
  let file = seen.get(url);
  if (!file) {
    file = `${slug}-${wght}-${seen.size}.woff2`; seen.set(url, file);
    await writeFile(new URL(`../public/fonts/${file}`, import.meta.url), Buffer.from(await (await fetch(url)).arrayBuffer()));
  }
  out += `@font-face{font-family:'${fam}';font-style:normal;font-weight:${/font-weight:\s*([^;]+)/.exec(body)[1].trim()};font-display:swap;src:url(../fonts/${file}) format('woff2');unicode-range:${/unicode-range:\s*([^;]+)/.exec(body)[1].trim()}}\n`;
}
await writeFile(new URL('../public/css/fonts.css', import.meta.url), out);
console.log([...seen.values()].join('\n'));
